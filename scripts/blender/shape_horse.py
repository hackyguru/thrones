"""Horse anatomy (a Marwari-type war horse, ~1.55 m at the withers) as an SDF sculpture.

  python3 scripts/blender/shape_horse.py <out.obj>
"""
import sys
from sdf import Sculpt


def horse(voxel=0.008):
    S = Sculpt((-0.42, -1.05, -0.01), (0.42, 1.6, 2.15), voxel)
    E, C, P = S.ellipsoid, S.cone, S.sphere
    # --- torso --------------------------------------------------------------------------------
    E((0, 0.0, 1.13), (0.27, 0.6, 0.32), k=0)
    E((0, 0.32, 1.08), (0.25, 0.36, 0.35), k=0.12)       # deep ribcage behind the elbow
    E((0, 0.62, 1.07), (0.2, 0.17, 0.27), k=0.1)          # breast
    E((0, -0.05, 0.92), (0.21, 0.45, 0.15), k=0.14)       # belly
    C((0, -0.45, 1.33), 0.17, (0, 0.22, 1.34), 0.15, k=0.12)  # back
    C((0, 0.22, 1.36), 0.1, (0, 0.52, 1.46), 0.09, k=0.08)    # withers
    E((0, -0.55, 1.27), (0.24, 0.3, 0.2), k=0.1)          # croup
    E((0, -0.82, 1.12), (0.19, 0.12, 0.22), k=0.08)       # buttocks
    for s in (1, -1):
        E((s * 0.12, -0.6, 1.12), (0.15, 0.3, 0.27), k=0.1, pitch=-0.25)       # haunch
        C((s * 0.15, 0.42, 1.36), 0.06, (s * 0.16, 0.62, 1.02), 0.1, k=0.13)   # sloping shoulder
        E((s * 0.155, 0.62, 0.97), (0.09, 0.1, 0.11), k=0.07)                   # point of shoulder / arm
    # --- neck ----------------------------------------------------------------------------------
    E((0, 0.72, 1.35), (0.15, 0.2, 0.25), k=0.1)
    S.chain([((0, 0.56, 1.28), 0.23), ((0, 0.84, 1.6), 0.14), ((0, 1.0, 1.84), 0.09)], k=0.1)
    C((0, 0.52, 1.5), 0.06, (0, 0.96, 1.87), 0.055, k=0.07)    # crest
    E((0, 0.8, 1.42), (0.08, 0.14, 0.12), k=0.08)               # throat / jugular groove
    # --- head (the face drops ~45° from poll to muzzle) ------------------------------------------
    E((0, 1.07, 1.83), (0.1, 0.12, 0.1), k=0.06)                # skull / forehead
    E((0, 1.22, 1.65), (0.078, 0.21, 0.07), k=0.05, pitch=-0.9)  # flat, broad face
    E((0, 1.355, 1.45), (0.075, 0.085, 0.08), k=0.05)           # muzzle
    E((0, 1.34, 1.385), (0.045, 0.05, 0.035), k=0.03)           # chin / lips
    C((0, 1.02, 1.7), 0.07, (0, 1.3, 1.41), 0.045, k=0.06)      # lower jaw
    for s in (1, -1):
        E((s * 0.05, 1.05, 1.7), (0.065, 0.13, 0.13), k=0.06)   # broad cheek / jowl
        E((s * 0.075, 1.11, 1.85), (0.035, 0.05, 0.035), k=0.03)  # brow ridge
        P((s * 0.088, 1.13, 1.82), 0.024, k=0.012, op='sub')       # eye socket
        P((s * 0.035, 1.42, 1.465), 0.018, k=0.012, op='sub')      # nostril
        C((s * 0.05, 0.99, 1.91), 0.032, (s * 0.068, 0.975, 2.05), 0.008, k=0.02)  # ear
    # --- front legs ----------------------------------------------------------------------------
    for s in (1, -1):
        x = s * 0.13
        C((x, 0.6, 0.98), 0.1, (x, 0.62, 0.56), 0.05, k=0.08)      # forearm
        E((x, 0.62, 0.525), (0.048, 0.05, 0.05), k=0.025)           # knee
        C((x, 0.62, 0.5), 0.037, (x, 0.62, 0.2), 0.033, k=0.02)     # cannon
        P((x, 0.624, 0.17), 0.045, k=0.02)                           # fetlock
        C((x, 0.63, 0.16), 0.032, (x, 0.665, 0.085), 0.034, k=0.015)  # pastern
        C((x, 0.67, 0.08), 0.043, (x, 0.685, 0.012), 0.054, k=0.01)   # hoof
    # --- hind legs -----------------------------------------------------------------------------
    for s in (1, -1):
        x = s * 0.12
        C((x, -0.55, 1.05), 0.16, (x, -0.63, 0.72), 0.1, k=0.1)   # thigh / gaskin
        E((s * 0.14, -0.4, 0.93), (0.07, 0.09, 0.09), k=0.1)       # stifle
        C((x, -0.64, 0.72), 0.085, (x, -0.75, 0.5), 0.05, k=0.05)  # gaskin to hock
        P((x, -0.79, 0.52), 0.042, k=0.03)                           # point of hock
        C((x, -0.74, 0.48), 0.04, (x, -0.71, 0.2), 0.033, k=0.025)  # hind cannon
        P((x, -0.705, 0.17), 0.045, k=0.02)
        C((x, -0.70, 0.16), 0.032, (x, -0.67, 0.085), 0.034, k=0.015)
        C((x, -0.665, 0.08), 0.043, (x, -0.655, 0.012), 0.053, k=0.01)
    # --- tail dock ------------------------------------------------------------------------------
    C((0, -0.84, 1.3), 0.06, (0, -0.93, 1.13), 0.035, k=0.05)
    S.clip_below(0.0)
    return S


if __name__ == '__main__':
    n = horse().save_obj(sys.argv[1])
    print('horse verts/faces', n)
